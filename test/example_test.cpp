// Tests the generated decode API against stock protobuf.
//
// Every message is built and serialized with stock protobuf, then decoded with
// wolaz, so this checks that wolaz reads exactly what the reference
// implementation writes.

#include <cstdint>
#include <cstdio>
#include <string>
#include <string_view>
#include <vector>

#include <wolaz.hpp>

#include "test/example.wolaz.hpp"    // wolaz
#include "test/example.pb.h"         // stock protobuf

namespace {

int failures = 0;

#define CHECK(cond)                                                       \
  do {                                                                    \
    if (!(cond)) {                                                        \
      std::fprintf(stderr, "%s:%d: CHECK failed: %s\n", __FILE__,         \
                   __LINE__, #cond);                                      \
      ++failures;                                                         \
    }                                                                     \
  } while (0)

#define CHECK_EQ(a, b)                                                    \
  do {                                                                    \
    auto va = (a);                                                        \
    auto vb = (b);                                                        \
    if (!(va == vb)) {                                                    \
      std::fprintf(stderr, "%s:%d: CHECK_EQ failed: %s != %s\n",          \
                   __FILE__, __LINE__, #a, #b);                           \
      ++failures;                                                         \
    }                                                                     \
  } while (0)

namespace wex = wolaz::example::decode;  // generated by protoc-gen-wolaz
namespace pex = wolaz::example;          // generated by the stock C++ backend

// -- the README's example ---------------------------------------------------

void test_readme_example() {
  pex::MSample ref;
  ref.set_onedouble(2.5);
  ref.set_twoint(7);
  ref.set_threestring("hello");
  ref.add_fourstrings("one");
  ref.add_fourstrings("two");
  ref.add_fourstrings("three");
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::MSample>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;

  CHECK(decoded->OneDouble.has_value());
  CHECK_EQ(*decoded->OneDouble, 2.5);
  CHECK_EQ(*decoded->TwoInt, std::int64_t{7});
  CHECK_EQ(*decoded->ThreeString, std::string_view("hello"));

  // The repeated field is iterated lazily, straight out of `bytes`.
  std::vector<std::string> got;
  for (wolaz::string_view s : decoded->FourStrings) got.emplace_back(s);
  CHECK_EQ(got.size(), std::size_t{3});
  if (got.size() == 3) {
    CHECK_EQ(got[0], std::string("one"));
    CHECK_EQ(got[2], std::string("three"));
  }

  // Strings are views into the caller's buffer, not copies.
  CHECK(decoded->ThreeString->data() >= bytes.data());
  CHECK(decoded->ThreeString->data() < bytes.data() + bytes.size());
}

// -- presence ---------------------------------------------------------------

void test_presence() {
  // Stock protobuf writes an explicit-presence zero, and omits an
  // implicit-presence zero. wolaz must report exactly that.
  pex::Coverage ref;
  ref.set_explicit_zero(0);
  ref.set_implicit_zero(0);
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;
  CHECK(decoded->explicit_zero.has_value());
  CHECK_EQ(*decoded->explicit_zero, 0);
  CHECK(!decoded->implicit_zero.has_value());

  // Nothing set at all: every field absent.
  auto empty = wolaz::decode<wex::Coverage>(std::string_view());
  CHECK(empty.has_value());
  if (empty) {
    CHECK(!empty->explicit_zero.has_value());
    CHECK(!empty->nested.has_value());
    CHECK(empty->nested_list.empty());
    CHECK(empty->choice_case == wex::Coverage::choice::NOT_SET);
  }
}

// -- nested, repeated message, recursion ------------------------------------

void test_nested_and_recursive() {
  pex::Coverage ref;
  ref.mutable_nested()->set_value(42);
  ref.mutable_nested()->add_numbers(1);
  ref.mutable_nested()->add_numbers(2);
  ref.mutable_nested()->add_numbers(3);
  ref.add_nested_list()->set_value(100);
  ref.add_nested_list()->set_value(200);
  ref.mutable_self()->set_implicit_zero(9);
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;

  CHECK(decoded->nested.has_value());
  auto nested = decoded->nested.get();
  CHECK(nested.has_value());
  if (nested) {
    CHECK_EQ(*nested->value, 42);
    std::vector<std::int32_t> ns;
    for (std::int32_t n : nested->numbers) ns.push_back(n);
    CHECK((ns == std::vector<std::int32_t>{1, 2, 3}));
  }

  // Repeated messages come back as undecoded handles.
  std::vector<std::int32_t> values;
  for (const auto& elem : decoded->nested_list) {
    auto e = elem.get();
    CHECK(e.has_value());
    if (e) values.push_back(e->value.value_or(-1));
  }
  CHECK((values == std::vector<std::int32_t>{100, 200}));

  // A field of the message's own type.
  CHECK(decoded->self.has_value());
  auto self_decoded = decoded->self.get();
  CHECK(self_decoded.has_value());
  if (self_decoded) CHECK_EQ(*self_decoded->implicit_zero, 9);
}

// -- enums, packed, bytes ---------------------------------------------------

void test_enums_and_packed() {
  pex::Coverage ref;
  ref.set_colour(pex::COLOUR_GREEN);
  ref.add_colours(pex::COLOUR_RED);
  ref.add_colours(pex::COLOUR_GREEN);
  ref.set_raw(std::string("\x00\x01\xff", 3));
  ref.add_packed_longs(1);
  ref.add_packed_longs(-1);
  ref.add_packed_longs(1LL << 40);
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;

  CHECK(decoded->colour.has_value());
  CHECK(*decoded->colour == wex::Colour::COLOUR_GREEN);

  std::vector<wex::Colour> colours;
  for (wex::Colour c : decoded->colours) colours.push_back(c);
  CHECK((colours ==
         std::vector<wex::Colour>{wex::Colour::COLOUR_RED,
                                  wex::Colour::COLOUR_GREEN}));

  CHECK(decoded->raw.has_value());
  CHECK_EQ(*decoded->raw, std::string_view("\x00\x01\xff", 3));

  // proto3 packs repeated scalars, so these arrive as one packed run.
  std::vector<std::int64_t> ls;
  for (std::int64_t l : decoded->packed_longs) ls.push_back(l);
  CHECK((ls == std::vector<std::int64_t>{1, -1, 1LL << 40}));
}

// -- oneof ------------------------------------------------------------------

void test_oneof() {
  // The discriminator says which member was set.
  pex::Coverage ref;
  ref.set_choice_string("picked");
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;
  CHECK(decoded->choice_case == wex::Coverage::choice::choice_string);
  CHECK(decoded->choice_string.has_value());
  CHECK_EQ(*decoded->choice_string, std::string_view("picked"));

  // A message member.
  pex::Coverage ref_msg;
  ref_msg.mutable_choice_message()->set_value(5);
  const std::string msg_bytes = ref_msg.SerializeAsString();
  auto decoded_msg =
      wolaz::decode<wex::Coverage>(std::string_view(msg_bytes));
  CHECK(decoded_msg.has_value());
  if (!decoded_msg) return;
  CHECK(decoded_msg->choice_case == wex::Coverage::choice::choice_message);
  auto inner = decoded_msg->choice_message.get();
  CHECK(inner.has_value());
  if (inner) CHECK_EQ(*inner->value, 5);
}

void test_oneof_last_wins() {
  // Two members on the wire: field 10 then field 11. The later one wins, even
  // though 10 has the lower field number. Stock protobuf never writes this, so
  // the bytes are spelled out, and stock protobuf confirms the expected winner.
  std::string bytes;
  bytes += '\x50';  // tag(10, varint)
  bytes += '\x07';  // 7
  bytes += '\x5a';  // tag(11, len)
  bytes += '\x03';
  bytes += "abc";

  pex::Coverage ref;
  CHECK(ref.ParseFromString(bytes));
  CHECK_EQ(static_cast<int>(ref.choice_case()),
           static_cast<int>(pex::Coverage::kChoiceString));

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;
  CHECK(decoded->choice_case == wex::Coverage::choice::choice_string);
  CHECK_EQ(*decoded->choice_string, std::string_view("abc"));
}

// -- maps -------------------------------------------------------------------

void test_map() {
  pex::Coverage ref;
  (*ref.mutable_counts())["a"] = 1;
  (*ref.mutable_counts())["b"] = 2;
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;

  // A map is a repeated field of entry messages on the wire, and that is how
  // it surfaces: no hashing, no allocation.
  int entries = 0;
  bool saw_a = false, saw_b = false;
  for (const auto& entry : decoded->counts) {
    auto e = entry.get();
    CHECK(e.has_value());
    if (!e) continue;
    ++entries;
    if (e->key.value_or("") == "a") saw_a = (*e->value == 1);
    if (e->key.value_or("") == "b") saw_b = (*e->value == 2);
  }
  CHECK_EQ(entries, 2);
  CHECK(saw_a);
  CHECK(saw_b);
}

// -- unknown fields ---------------------------------------------------------

void test_unknown_fields_are_skipped() {
  // Field 31 is not declared in Coverage. wolaz skips it, and the fields
  // around it still decode.
  pex::Coverage ref;
  ref.set_implicit_zero(5);
  ref.set_colour(pex::COLOUR_RED);
  ref.mutable_unknown_fields()->AddVarint(31, 42);
  const std::string bytes = ref.SerializeAsString();

  auto decoded = wolaz::decode<wex::Coverage>(std::string_view(bytes));
  CHECK(decoded.has_value());
  if (!decoded) return;
  CHECK_EQ(*decoded->implicit_zero, 5);
  CHECK(*decoded->colour == wex::Colour::COLOUR_RED);
}

// -- malformed input --------------------------------------------------------

void test_malformed_input_is_rejected() {
  // Truncated length-delimited payload: field 3 claims five bytes, supplies
  // two. The escapes are split because hex escapes are greedy -- "\x05ab"
  // would be read as a single out-of-range escape.
  const std::string truncated("\x1a\x05" "ab", 4);
  CHECK(!wolaz::decode<wex::Coverage>(std::string_view(truncated)));

  // Invalid UTF-8 in a `string` field (field 3 of MSample).
  const std::string bad_utf8("\x1a\x01\x80", 3);
  auto r = wolaz::decode<wex::MSample>(std::string_view(bad_utf8));
  CHECK(!r);
  CHECK(r.error() == wolaz::err::invalid_utf8);
  CHECK(r.error() == "string field is not valid UTF-8");

  // The same bytes in a `bytes` field (field 7 of Coverage) are fine.
  const std::string ok_bytes("\x3a\x01\x80", 3);
  CHECK(wolaz::decode<wex::Coverage>(std::string_view(ok_bytes)));
}

}  // namespace

int main() {
  test_readme_example();
  test_presence();
  test_nested_and_recursive();
  test_enums_and_packed();
  test_oneof();
  test_oneof_last_wins();
  test_map();
  test_unknown_fields_are_skipped();
  test_malformed_input_is_rejected();

  if (failures != 0) {
    std::fprintf(stderr, "\n%d check(s) failed\n", failures);
    return 1;
  }
  std::printf("all generated-code tests passed\n");
  return 0;
}
